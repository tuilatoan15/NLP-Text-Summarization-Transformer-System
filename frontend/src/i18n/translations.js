export function t(locale, key, vars = {}) {
  const table = translations[locale] || translations.vie;
  let text = table[key] ?? translations.vie[key] ?? translations.eng[key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    text = text.replaceAll(`{${k}}`, String(v));
  });
  return text;
}
